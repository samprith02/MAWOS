def f8_latency_cdf():
    """Where the time actually goes, per query.

    The hybrid curve is not a model of a mixture, it is the mixture: each
    dev task is charged the lexicon pass, plus that task's own measured LLM
    call if and only if its margin escalates it. So the step in the curve
    sits exactly at the escalation rate, and the tail is the real tail of
    the 3B, not a fitted one.
    """
    v2 = load(V2 / "baseline.json")
    sweep = load(GATES / "p6_sweep.json")
    lex_ms = float(np.mean([s["wall_ms"] for s in v2["routing"]["per_seed"]])
                   / v2["routing"]["n_queries"])
    elig = {m["model"]: m["eligible"]
            for m in sweep["eligible_models"] + sweep["out_of_competition"]}

    fr = dev_frame()
    tau = fr["tau"]
    lat_by_task = {}
    for r in fr["capture"]["records"]:
        lat_by_task.setdefault(r["task_id"], []).append(r["latency_ms"])
    hybrid = []
    for t in fr["tasks"]:
        if fr["margins"][t.id] <= tau:
            hybrid += [lex_ms + x for x in lat_by_task[t.id]]
        else:
            hybrid += [lex_ms] * len(fr["capture"]["seeds"])

    fig, ax = plt.subplots(figsize=(9.4, 5.0))

    def ecdf(vals, **kw):
        v = np.sort(np.asarray(vals, dtype=float))
        y = np.arange(1, len(v) + 1) / len(v) * 100
        ax.step(v, y, where="post", **kw)
        return v

    ecdf([lex_ms] * 108, color=C_LEX, lw=6.0, alpha=0.42,
         label="lexicon only (n=108)")
    hv = ecdf(hybrid, color=C_HYB, lw=2.2,
              label="hybrid at tau=%g (n=%d)" % (tau, len(hybrid)))
    shades = {"qwen2.5:1.5b-instruct": "#e8a08c",
              "qwen2.5:3b-instruct": C_LLM,
              "qwen2.5:7b-instruct": "#8c3b28"}
    for name, path in CAPTURES.items():
        cap = load(path)
        vals = [r["latency_ms"] for r in cap["records"]]
        ok = elig.get(name, True)
        ecdf(vals, color=shades[name], lw=1.5 if ok else 1.2,
             ls="-" if ok else (0, (4, 2)), alpha=1.0 if ok else 0.75,
             label="LLM only %s (n=%d)%s"
                   % (name.split(":")[1].replace("-instruct", "").upper(),
                      len(vals), "" if ok else " - out of competition"))

    esc = float(np.mean([fr["margins"][t.id] <= tau for t in fr["tasks"]])) * 100
    ax.axhline(100 - esc, color="#888888", ls=":", lw=1.1)
    ax.annotate("%.1f%% of queries never reach the LLM" % (100 - esc)
                + chr(10) + "and are answered in %.2f ms" % lex_ms,
                xy=(lex_ms * 2.2, 100 - esc), xytext=(0.35, 62),
                fontsize=7.8, color=C_HYB,
                arrowprops=dict(arrowstyle="-|>", color=C_HYB, lw=0.9,
                                connectionstyle="arc3,rad=-0.2"))
    ax.annotate("the hybrid's tail IS the 3B's tail" + chr(10)
                + "%.1f%% of queries, median %.0f ms"
                % (esc, float(np.median([x for x in hv if x > 1]))),
                xy=(float(np.percentile([x for x in hv if x > 1], 50)), 96),
                xytext=(3.0, 34), fontsize=7.8, color=C_HYB,
                arrowprops=dict(arrowstyle="-|>", color=C_HYB, lw=0.9,
                                connectionstyle="arc3,rad=0.2"))

    ax.set_xscale("log")
    ax.set_xlim(0.03, 12000)
    ax.set_ylim(0, 103)
    ax.set_xlabel("per-query latency (ms, log scale)")
    ax.set_ylabel("queries at or below this latency (%)")
    ax.set_title("F8 " + chr(8212) + " latency distribution by routing tier",
                 loc="left")
    ax.legend(loc="lower right", bbox_to_anchor=(0.60, 0.03),
              fontsize=7.6)
    clean(ax, grid_axis="both")

    caption(fig,
            "Dev split, 3 seeds. LLM curves are the measured per-call "
            "latencies from the frozen captures, all taken with the model "
            "GPU-resident; the 7B is dashed because it was not (81.7%%) and "
            "its latency is not comparable \u2014 it is drawn for shape "
            "only. The lexicon timing comes from the v2 freeze, recorded "
            "with no model resident, which is the one cross-condition "
            "number here; it is %.2f ms against a %.0f ms LLM call, so it "
            "cannot change the picture. CLAUDE.md's warning about cascade "
            "latency (127 ms idle vs 466 ms with a 2 GB model loaded) is "
            "about the agent cascade, not this classification path."
            % (lex_ms, float(np.median([x for x in hv if x > 1]))))
    return fig, {
        "sources": ["evaluation/results/v3_llm/*.json",
                    "evaluation/results/v2_frozen/baseline.json",
                    "evaluation/results/v3_gates/p6_sweep.json"],
        "note": "%.1f%% of queries answered in %.2f ms; escalated tail "
                "median %.0f ms" % (100 - esc, lex_ms,
                                    float(np.median([x for x in hv if x > 1]))),
    }


