def f6_pareto():
    """The complete threshold curve, and what it costs.

    Published in full because the reviewer asked for the selection to be
    auditable: every achievable operating point is here, not just the one
    that was chosen. The 7B is deliberately absent — it was not
    GPU-resident, so its latency is not measured under the same conditions
    and it must not share a frontier with an eligible model.
    """
    p4 = load(GATES / "p4_router.json")
    sweep = load(GATES / "p6_sweep.json")
    v2 = load(V2 / "baseline.json")

    from evaluation.benchmark.tasks import DEV_TASKS
    if p4["n"] != len(DEV_TASKS):
        raise Blocked(
            f"p4_router.json was tuned against n={p4['n']} dev tasks, but "
            f"evaluation/benchmark/tasks.py now has {len(DEV_TASKS)} -- a "
            "pre-P2 tau selection (108 tasks/13 tools) read against the "
            "post-P2 instrument (99 tasks/12 tools). Needs a fresh "
            "tune_router.py run, which itself needs a GPU-resident "
            "capture_llm.py run first.")

    model = next(m for m in sweep["eligible_models"]
                 if m["model"] == SELECTED_MODEL)
    llm_ms = model["latency_median_ms"]
    lex_ms = float(np.mean([s["wall_ms"] for s in v2["routing"]["per_seed"]])
                   / v2["routing"]["n_queries"])

    pts = p4["curve"]
    tau = np.array([p["tau"] for p in pts])
    acc = np.array([p["accuracy_mean"] for p in pts]) * 100
    sd = np.array([p["accuracy_std"] for p in pts]) * 100
    esc = np.array([p["escalation_rate"] for p in pts])
    feas = np.array([p["feasible"] for p in pts])
    lat = (1 - esc) * lex_ms + esc * llm_ms
    sel = p4["selected"]
    star = p4["argmax"]
    cut = (star["accuracy_mean"] - p4["sigma_at_argmax"]) * 100
    k = int(np.argmin(np.abs(tau - sel["tau"])))

    fig, (axa, axb) = plt.subplots(1, 2, figsize=(12.4, 4.8))

    axa.axvspan(3.0 - 0.25, tau.max() + 0.4, color="#f4dede", alpha=0.6, lw=0)
    axa.text(tau.max() - 0.1, 66.5, "above the 50% escalation cap"
             + chr(10) + "(PROTOCOL 9.1) " + chr(8212) + " excluded",
             ha="right", fontsize=7.2, color="#8a3b2f", style="italic")
    axa.fill_between(tau, acc - sd, acc + sd, color=C_HYB, alpha=0.16, lw=0)
    axa.plot(tau, acc, "-", color=C_HYB, lw=1.5, zorder=3)
    axa.plot(tau[feas], acc[feas], "o", color=C_HYB, ms=5, zorder=4)
    axa.plot(tau[~feas], acc[~feas], "o", mfc="white", mec=C_HYB, ms=5,
             zorder=4)
    axa.axhline(p4["lexicon_accuracy"] * 100, color=C_LEX, ls="--", lw=1.4)
    axa.text(tau.max(), p4["lexicon_accuracy"] * 100 + 1.0, "lexicon alone",
             color=C_LEX, fontsize=7.8, ha="right", fontweight="bold")
    axa.axhline(cut, color="#a06a1e", ls=":", lw=1.3)
    axa.text(tau.max() + 0.3, cut + 0.9, "A* minus one sd " + chr(8212)
             + " the 1-SE rule's floor", color="#a06a1e", fontsize=7.4,
             ha="right")
    axa.plot([sel["tau"]], [sel["accuracy_mean"] * 100], "*", ms=17,
             color="#c9a227", mec="#6b5410", mew=0.8, zorder=6)
    axa.annotate("selected tau = %g" % sel["tau"] + chr(10)
                 + "%.1f%% at %.1f%% escalation"
                 % (sel["accuracy_mean"] * 100, sel["escalation_rate"] * 100),
                 xy=(sel["tau"], sel["accuracy_mean"] * 100),
                 xytext=(1.35, 99.5), fontsize=7.6, color="#6b5410",
                 arrowprops=dict(arrowstyle="-|>", color="#6b5410", lw=0.9,
                                 connectionstyle="arc3,rad=0.25"))
    axa.set_xlabel("tau (escalate when lexicon margin <= tau)")
    axa.set_ylabel("hybrid accuracy on dev (%)")
    axa.set_ylim(65, 103)
    axa.set_title("A " + chr(8212) + " every achievable operating point",
                  loc="left")
    clean(axa, grid_axis="both")

    axb.plot(lat[feas], acc[feas], "-o", color=C_HYB, lw=1.4, ms=5, zorder=3,
             label="hybrid, feasible tau")
    axb.plot(lat[~feas], acc[~feas], "--o", color=C_HYB, lw=1.0, ms=4.5,
             mfc="white", alpha=0.65, zorder=2, label="hybrid, above the cap")
    axb.plot([lat[0]], [acc[0]], "s", color=C_LEX, ms=8, zorder=5)
    axb.annotate("lexicon only" + chr(10) + "%.2f ms" % lex_ms,
                 xy=(lat[0], acc[0]), xytext=(lat[0] * 1.5, 84.5),
                 fontsize=7.6, color=C_LEX, ha="left",
                 arrowprops=dict(arrowstyle="-|>", color=C_LEX, lw=0.9))
    axb.plot([lat[-1]], [acc[-1]], "s", color=C_LLM, ms=8, zorder=5)
