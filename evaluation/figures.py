def dev_frame(model=SELECTED_MODEL):
    """Per-task lexicon / LLM / hybrid correctness on the dev split.

    Recomputed from the frozen lexicon and the frozen capture rather than
    read from a summary, so a figure can never disagree with the JSON it
    claims to plot. `tau` comes from the deployed config, not from a
    literal here — if the config is edited the figures move with it, which
    is the intended tripwire.
    """
    from evaluation.baselines import lexicon_v2
    from evaluation.benchmark.tasks import DEV_TASKS
    from evaluation.gate_p05 import margins

    cap = load(CAPTURES[model])
    dev_ids = {t.id for t in DEV_TASKS}
    cap_ids = {r["task_id"] for r in cap["records"]}
    if cap_ids != dev_ids:
        raise Blocked(
            f"{CAPTURES[model].name} was captured against a different dev "
            f"task set than the one currently frozen ({len(cap_ids)} task "
            f"IDs in the capture vs {len(dev_ids)} in "
            "evaluation/benchmark/tasks.py) -- most likely a pre-P2 "
            "capture (108 tasks/13 tools) read against the post-P2 "
            "instrument (99 tasks/12 tools). Needs a fresh capture: "
            "capture_llm.py + tune_router.py against the current instrument.")
    if not (cap.get("gpu_residency") or {}).get("fully_resident"):
        raise Blocked(
            f"{CAPTURES[model].name} is not GPU-resident "
            f"(gpu_residency.fully_resident is not true) -- PROTOCOL Sec9.2 "
            "makes this a hard ineligibility, and a figure drawn from it "
            "would silently present a CPU-timing artifact as the real "
            "result. Needs a GPU-resident recapture.")
    tau = json.loads((ROOT / "backend" / "app" / "router_config.json")
                     .read_text(encoding="utf-8"))["tau"]
    marg = margins()
    lex = {t.id: lexicon_v2.classify_keyword(t.query).intent == t.gold_intent
           for t in DEV_TASKS}
    llm = {s: {r["task_id"]: r["outcome"] == "correct"
               for r in cap["records"] if r["seed"] == s}
           for s in cap["seeds"]}
    hyb = {s: {i: (llm[s][i] if marg[i] <= tau else lex[i]) for i in lex}
           for s in cap["seeds"]}
    return {
        "tasks": DEV_TASKS, "capture": cap, "tau": tau, "margins": marg,
        "lex": lex, "llm": llm, "hyb": hyb, "seeds": cap["seeds"],
        "stratum": {t.id: t.stratum for t in DEV_TASKS},
    }


def _rate(ok_by_seed, ids):
    """Mean and population sd of accuracy over seeds, restricted to `ids`."""
    per = [sum(ok[i] for i in ids) / len(ids) for ok in ok_by_seed.values()]
    return float(np.mean(per)), float(np.std(per))


