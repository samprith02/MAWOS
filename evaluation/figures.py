def _bus_graph():
    """Publisher -> topic -> subscriber, read out of the running system.

    Subscriptions come from the live bus after the real registry is
    constructed, so the figure cannot drift from the wiring. Publications
    are read from the agent sources, because a publish only happens inside
    a handler and there is no registry to introspect.
    """
    import re
    from backend.app.agents import get_agents
    from backend.app.bus import bus

    get_agents()
    subs: dict[str, list[str]] = {t: [a for a, _ in hs]
                                  for t, hs in bus._subscribers.items()}

    pubs: dict[str, list[str]] = {}
    for src in sorted((ROOT / "backend" / "app" / "agents").glob("*.py")):
        if src.name in ("__init__.py", "base.py"):
            continue
        text = src.read_text(encoding="utf-8")
        m = re.search(r'^\s*name\s*=\s*"([^"]+)"', text, re.M)
        if not m:
            continue
        agent = m.group(1)
        for topic in re.findall(r'self\.publish\(\s*"([^"]+)"', text):
            pubs.setdefault(topic, [])
            if agent not in pubs[topic]:
                pubs[topic].append(agent)

    edges = []
    for topic, targets in subs.items():
        for tgt in targets:
            for srcagent in pubs.get(topic, ["(external)"]):
                edges.append((srcagent, tgt, topic))
    sinks = sorted(t for t in pubs if t not in subs)
    return pubs, subs, edges, sinks


def _layer(edges, nodes):
    """Longest-path layering, ignoring self-loops."""
    real = [(a, b) for a, b, _ in edges if a != b]
    level = {n: 0 for n in nodes}
    for _ in range(len(nodes) + 1):
        changed = False
        for a, b in real:
            if a in level and level.get(b, 0) < level[a] + 1:
                level[b] = level[a] + 1
                changed = True
        if not changed:
            break
    return level


def _spread(ys, gap):
    """Push overlapping labels apart, preserving order."""
    order = sorted(range(len(ys)), key=lambda i: ys[i])
    out = list(ys)
    for k in range(1, len(order)):
        prev, cur = order[k - 1], order[k]
        if out[cur] - out[prev] < gap:
            out[cur] = out[prev] + gap
    return out


def f1_cascade_dag():
    """Agents in columns by hop, topics as pills on the lanes between.

    Drawing the topic once, rather than once per subscriber, is the whole
    point: `attendance.updated` having four subscribers is the fan-out the
    architecture claims, and four separate arrows labelled with the same
    string hide it.
    """
    from backend.app.agents import get_agents
    pubs, subs, edges, sinks = _bus_graph()
    total_agents = len(get_agents())

    nodes = sorted({a for a, _, _ in edges} | {b for _, b, _ in edges})
    level = _layer(edges, nodes)
    depth = max(level.values())

    cols = {}
    for n in sorted(nodes, key=lambda n: (level[n], n)):
        cols.setdefault(level[n], []).append(n)
    span = max(len(v) for v in cols.values())

    apos = {}
    for lv, members in cols.items():
        for i, n in enumerate(members):
            y = -(span - 1) / 2 if len(members) == 1 else                 -(i * (span - 1) / (len(members) - 1))
            apos[n] = (lv * 4.6, y * 1.25)

    # A topic sits on the lane after its publisher, unless it is consumed
    # by the agent that published it, in which case it is an ingest topic
    # and sits on the lane before.
    lanes = {}
    for topic, srcs in pubs.items():
        pub = srcs[0]
        selfloop = subs.get(topic) == [pub]
        x = apos[pub][0] + (-2.3 if selfloop else 2.3)
        want = [apos[pub][1]] + [apos[s][1] for s in subs.get(topic, [])]
        lanes.setdefault(x, []).append((topic, sum(want) / len(want), pub))

    tpos = {}
    for x, items in lanes.items():
        items.sort(key=lambda it: -it[1])
        ys = _spread([-it[1] for it in items], 0.62)
        for (topic, _, _), y in zip(items, ys):
            tpos[topic] = (x, -y)

    fig, ax = plt.subplots(figsize=(12.4, 5.2))

    def arrow(p0, p1, color, lw=1.0, alpha=1.0):
        ax.annotate("", xy=p1, xytext=p0, zorder=2,
                    arrowprops=dict(arrowstyle="-|>", lw=lw, color=color,
                                    alpha=alpha, shrinkA=3, shrinkB=3,
                                    connectionstyle="arc3,rad=0.0"))

    for topic, (tx, ty) in tpos.items():
        pub = pubs[topic][0]
        px, py = apos[pub]
        dead = topic in sinks
        col = "#c0a060" if dead else "#8496ad"
        if tx < px:
            # Ingest topic: published and consumed by the same agent, so the
            # publish arrow has to leave the box on the same side it re-enters.
            ax.annotate("", xy=(tx, ty - 0.22), xytext=(px - 1.15, py - 0.12),
                        zorder=2,
                        arrowprops=dict(arrowstyle="-|>", lw=1.0, color=col,
                                        alpha=0.9, shrinkA=3, shrinkB=3,
                                        connectionstyle="arc3,rad=0.45"))
        else:
            arrow((px + 1.15, py), (tx - 0.02, ty), col, alpha=0.9)
        for sub in subs.get(topic, []):
            sx, sy = apos[sub]
            if tx < px:
                arrow((tx + 0.02, ty), (sx - 1.15, sy), col, alpha=0.9)
            else:
                arrow((tx + 0.02, ty), (sx - 1.15, sy), col, alpha=0.9)
        ax.text(tx, ty, topic, ha="center", va="center", fontsize=6.8,
                zorder=4, color="#7a6a3a" if dead else "#3d4a5c",
                style="italic" if dead else "normal",
                bbox=dict(boxstyle="round,pad=0.28", fc="#fdf8ec" if dead
                          else "#eef3f8", ec=col, lw=0.8))

    for n in nodes:
        x, y = apos[n]
        ax.add_patch(plt.Rectangle((x - 1.15, y - 0.27), 2.3, 0.54,
                                   fc="#dce7f2" if level[n] == 0 else "#f2f5f8",
                                   ec=C_HYB, lw=1.2, zorder=3))
        ax.text(x, y, n.replace("_agent", ""), ha="center", va="center",
                fontsize=8.4, zorder=4,
                fontweight="bold" if level[n] == 0 else "normal")

    top = max(y for _, y in list(apos.values()) + list(tpos.values()))
    for lv in sorted(cols):
        ax.text(lv * 4.6, top + 0.95, f"hop {lv}", ha="center", fontsize=8.5,
                color="#777777", fontweight="bold")

    lo = min(y for _, y in list(apos.values()) + list(tpos.values()))
    ax.set_xlim(-4.0, depth * 4.6 + 3.8)
    ax.set_ylim(lo - 0.5, top + 1.35)
    ax.axis("off")
    ax.set_title("F1 — event cascade: who publishes what, and who wakes up",
                 loc="left")
    caption(fig,
            f"Read from the live bus after the real registry is built. "
            f"{len(nodes)} of {total_agents} agents participate in cascades "
            f"(academic and orchestrator are request-response only); "
            f"{len(subs)} topics have subscribers, {len(sinks)} are published "
            f"with none (amber, italic — they terminate the cascade). "
            f"Longest chain is {depth} hops. The bus is in-process and "
            f"at-most-once: an exception in one subscriber is isolated, but a "
            f"crash between hops loses the event and replay is manual.")
    return fig, {
        "sources": ["backend/app/bus.py", "backend/app/agents/*.py"],
        "note": f"{len(nodes)}/{total_agents} agents in cascades, "
                f"{len(edges)} edges, {len(sinks)} sink topics, depth {depth}",
    }


